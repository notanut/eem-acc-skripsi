"""Chapter IV analysis for RQ2 (design v2): every table and figure from the stored results + the frozen file.

Usage (repo root):  PYTHONPATH=src python experiments/analyze_rq2.py --root <ROOT>
Reads <ROOT>/results/rq2/{dev,test,boundary}/units and configs/rq2_frozen.json (must equal the root's copy).
Writes <ROOT>/analysis/: *.csv, rq2_tables.md, figures/*.pdf|png. Deterministic; re-running overwrites.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from eem_acc import rq2_figures as F                                      # noqa: E402
from eem_acc import rq2_report as R                                       # noqa: E402
from eem_acc.analysis import (boundary_report, load_results, primary_comparisons,   # noqa: E402
                              robustness_matrix, test_descriptive)


def analyze(root: Path, frozen: dict, figures: bool = True) -> dict[str, Path]:
    rr = root / "results" / "rq2"
    out = root / "analysis"
    (out / "figures").mkdir(parents=True, exist_ok=True)
    test = load_results(rr / "test" / "units")
    if test.empty:
        raise SystemExit("no test results: run --phase test first")
    tables = {
        "primary_comparisons": primary_comparisons(test, frozen),
        "cell_table": R.cell_table(test, frozen),
        "event_windows": R.event_table(test, frozen),
        "recovery": R.recovery_table(test, frozen),
        "test_descriptive": test_descriptive(test, frozen),
        "robustness_matrix": robustness_matrix(test, frozen),
        "loso_dev": R.loso_table(frozen),
    }
    bdir = rr / "boundary" / "units"
    if bdir.exists() and any(bdir.glob("*.json")):
        tables["boundary_dev"] = boundary_report(load_results(rr / "dev" / "units"), load_results(bdir), frozen)
    written = {}
    md = ["# RQ2 tables (generated by experiments/analyze_rq2.py; do not edit by hand)\n"]
    for name, df in tables.items():
        p = out / f"{name}.csv"
        df.to_csv(p, index=False)
        written[name] = p
        md += [f"\n## {name}\n", R.to_markdown(df)]
    (out / "rq2_tables.md").write_text("\n".join(md) + "\n")
    written["markdown"] = out / "rq2_tables.md"
    if figures:
        F.save(F.timeseries_figure(frozen, stored=test), str(out / "figures" / "fig_rq2_timeseries"))
        F.save(F.frontier_figure(tables["test_descriptive"], frozen), str(out / "figures" / "fig_rq2_frontier"))
        F.save(F.robustness_heatmap(tables["robustness_matrix"]), str(out / "figures" / "fig_rq2_robustness"))
        written["figures"] = out / "figures"
    return written


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--no-figures", action="store_true")
    args = ap.parse_args()
    root = Path(args.root)
    repo_copy = json.loads((REPO / "configs" / "rq2_frozen.json").read_text())
    run_copy_p = root / "results" / "rq2" / "rq2_frozen.json"
    if run_copy_p.exists() and json.loads(run_copy_p.read_text()) != repo_copy:
        print("[analyze] refusing: the root's frozen file differs from configs/rq2_frozen.json")
        return 2
    for k, v in analyze(root, repo_copy, figures=not args.no_figures).items():
        print(f"[analyze] {k}: {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
