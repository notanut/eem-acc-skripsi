"""Chapter IV analysis for RQ2 (design v2): every table and figure from the stored results + the frozen file.

Usage (repo root):  PYTHONPATH=src python experiments/analyze_rq2.py --root <ROOT>
Reads <ROOT>/results/rq2/{dev,test,boundary}/units and configs/rq2_frozen.json (must equal the root's copy).
Writes <ROOT>/analysis/: *.csv, rq2_tables.md, figures/*.pdf|png. Deterministic; re-running overwrites.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from eem_acc import rq2_figures as F                                      # noqa: E402
from eem_acc import rq2_report as R                                       # noqa: E402
from eem_acc.analysis import (boundary_report, load_results, primary_comparisons,   # noqa: E402
                              robustness_matrix, test_descriptive)


def analyze(root: Path, frozen: dict, figures: bool = True) -> dict[str, Path]:
    rr = root / "results" / "rq2"
    out = root / "analysis"
    (out / "figures").mkdir(parents=True, exist_ok=True)
    test = load_results(rr / "test" / "units")
    if test.empty:
        raise SystemExit("no test results: run --phase test first")
    tables = {
        "primary_comparisons": primary_comparisons(test, frozen),
        "cell_table": R.cell_table(test, frozen),
        "event_windows": R.event_table(test, frozen),
        "recovery": R.recovery_table(test, frozen),
        "test_descriptive": test_descriptive(test, frozen),
        "robustness_matrix": robustness_matrix(test, frozen),
        "loso_dev": R.loso_table(frozen),
        "pareto_dev": R.pareto_table(frozen),
    }
    dev_dir = rr / "dev" / "units"
    dev = load_results(dev_dir) if dev_dir.exists() else None
    tables["reporting_facts"] = R.reporting_facts(frozen, dev, test)
    bdir = rr / "boundary" / "units"
    if bdir.exists() and any(bdir.glob("*.json")):
        tables["boundary_dev"] = boundary_report(dev, load_results(bdir), frozen)
    known = {f"{n}.csv" for n in tables} | {"rq2_tables.md", "figure_captions.md"}
    for p in out.glob("*"):                       # outputs of earlier versions must not be mistaken for current ones
        if p.is_file() and p.name not in known:
            p.unlink()
    written = {}
    md = ["# RQ2 tables (generated by experiments/analyze_rq2.py; do not edit by hand)\n"]
    for name, df in tables.items():
        p = out / f"{name}.csv"
        df.to_csv(p, index=False)
        written[name] = p
        md += [f"\n## {name}\n", R.to_markdown(df)]
    (out / "rq2_tables.md").write_text("\n".join(md) + "\n")
    written["markdown"] = out / "rq2_tables.md"
    if figures:
        F.save(F.timeseries_figure(frozen, stored=test), str(out / "figures" / "fig_rq2_timeseries"))
        F.save(F.frontier_figure(tables["test_descriptive"], frozen), str(out / "figures" / "fig_rq2_frontier"))
        F.save(F.robustness_heatmap(tables["robustness_matrix"]), str(out / "figures" / "fig_rq2_robustness"))
        written["figures"] = out / "figures"
    (out / "figure_captions.md").write_text(CAPTIONS)
    written["captions"] = out / "figure_captions.md"
    return written


CAPTIONS = """# Figure captions (draft for Chapter IV)

**fig_rq2_timeseries.** One test seed (100), M = 32, frozen ACC vs the scenario's best fixed window and the global fixed
window (W = 4). Top: window limit in force at dispatch, averaged per 2-s bin; when demand does not fill it (above the
dotted M line) the window does not constrain anything and keeps growing up to W_max = 128 (window inflation), which is
why the p95 latency spike after the capacity drop lasts several seconds. Middle: successful calls completed per second.
Bottom: p95 latency of HTTP 200 attempts and client timeouts per 2-s bin; dashed line: SLO (0.45 s). Shaded: event.
The re-simulated runs are checked to equal the stored test results.

**fig_rq2_frontier.** All test methods (10 test seeds): score = mean over the 8 loaded cells of goodput normalised by the
frozen dev denominators; x = worst loaded-cell SLO violation (log scale; values below 0.1% drawn at 0.1%). Filled =
meets all three limits (SLO <= 5%, success >= 99%, overload <= 10%) in every loaded cell; open markers may fail on
success or overload even when they lie left of the 5% line (e.g. W = 4 and 15/s fail call success in CAP-burst).

**fig_rq2_robustness.** Normalised goodput (mean over the scenario's loaded cells, test seeds) of the key methods; x and
hatching: the method violates a limit in some loaded cell of that scenario. Values above 1 occur because the
denominators are the best goodput of a FEASIBLE dev method; the colour scale clips at 1.05.
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--no-figures", action="store_true")
    args = ap.parse_args()
    root = Path(args.root)
    repo_copy = json.loads((REPO / "configs" / "rq2_frozen.json").read_text())
    run_copy_p = root / "results" / "rq2" / "rq2_frozen.json"
    if run_copy_p.exists() and json.loads(run_copy_p.read_text()) != repo_copy:
        print("[analyze] refusing: the root's frozen file differs from configs/rq2_frozen.json")
        return 2
    for k, v in analyze(root, repo_copy, figures=not args.no_figures).items():
        print(f"[analyze] {k}: {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
