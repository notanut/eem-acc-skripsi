"""Write the S3.1 evidence files (frozen with the suite):

* docs/evidence/s31_drift_pools.json: the dev/test pools and every pair's concrete change;
* docs/evidence/s31_subgoals.md: per template, its covered operations, an example instruction, reference plan and
  sub-goal names (for review);
* docs/evidence/s31_template_mix.json: realised template shares and mean min_calls over the seed ranges;
* docs/evidence/s31_drift_usage.json: per-pair frequencies in the planned streams (joint drawing, D86).

Usage: PYTHONPATH=src python tools/make_s31_evidence.py
"""
from __future__ import annotations

import json
import random
import statistics
from collections import Counter
from pathlib import Path

from eem_acc.stage3.apisuite.drift import ALL_PAIRS, POOLS
from eem_acc.stage3.apisuite.oracle import OracleAPI, check, reference_plan, scratch_suite
from eem_acc.stage3.apisuite.streams import SEED_RANGES, SUITE_VERSION, drift_usage, sample_stream

PLANNED = {"rq1/test": ("rq1", "test", 14), "rq1/dev": ("rq1", "dev", 10), "sp/test": ("sp", "test", 5),
           "rq3/test": ("rq3", "test", 10), "rq3/dev": ("rq3", "dev", 2)}
from eem_acc.stage3.apisuite.templates import TEMPLATES, Gen, sample_instance

OUT = Path(__file__).resolve().parents[1] / "docs" / "evidence"


def pools() -> None:
    data = {"suite_version": SUITE_VERSION, "pools": POOLS,
            "pairs": {i: ALL_PAIRS[i].as_json() for i in sorted(ALL_PAIRS)}}
    (OUT / "s31_drift_pools.json").write_text(json.dumps(data, indent=1, sort_keys=True) + "\n")


def subgoals() -> None:
    lines = [f"# S3.1 templates: example instances, reference plans, sub-goals ({SUITE_VERSION})", "",
             "Generated by `tools/make_s31_evidence.py` (one example per template and outcome).", ""]
    for tid, tpl in TEMPLATES.items():
        seen = set()
        for k in range(200):
            inst = sample_instance(tid, Gen(random.Random(f"evidence:{tid}:{k}"), 2), 0)
            oc = inst.get("outcome", "-")
            if oc in seen:
                continue
            seen.add(oc)
            s = scratch_suite(inst)
            api = OracleAPI(s, 0)
            tpl.solve(api, inst)
            ok, goals = check(inst, s.world)
            assert ok
            lines += [f"## {tid}" + (f" (outcome: {oc})" if oc != "-" else ""), "",
                      f"- covers: {', '.join(sorted(tpl.covers))}",
                      f"- instruction: {inst['instruction']}",
                      f"- reference plan ({len(api.trace)} calls): {', '.join(op for op, _ in api.trace)}",
                      f"- sub-goals: {'; '.join(name for name, _ in goals)}", ""]
            if len(seen) >= 2 or "outcome" not in inst:
                break
    (OUT / "s31_subgoals.md").write_text("\n".join(lines))


def mix() -> None:
    out = {}
    for (kind, split), rng in SEED_RANGES.items():
        c, calls = Counter(), []
        for seed in rng:
            s = sample_stream(seed, split, kind=kind)
            c.update(t["template"] for t in s["tasks"])
            calls += [len(reference_plan(t)) for t in s["tasks"]]
        n = sum(c.values())
        out[f"{kind}/{split}"] = {"streams": len(rng), "mean_min_calls": round(statistics.mean(calls), 3),
                                  "share_vs_uniform": {t: round(c[t] / n * len(TEMPLATES), 3)
                                                       for t in sorted(TEMPLATES)}}
    (OUT / "s31_template_mix.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")


def usage() -> None:
    out = {name: drift_usage(*args) for name, args in PLANNED.items()}
    (OUT / "s31_drift_usage.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    pools()
    subgoals()
    mix()
    usage()
    print("written:", [p.name for p in sorted(OUT.glob("s31_*"))])
